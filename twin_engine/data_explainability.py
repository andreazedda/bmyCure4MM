    unit = ASSESSMENT_FIELD_UNITS.get(field_name, "")
    for assessment in patient.assessments.order_by("-date"):
        value = getattr(assessment, field_name, None)
        if value is None:
            continue
        rows.append(
            _row(
                date_obj=assessment.date,
                field=label,
                value=_format_scalar(value),
                unit=unit,
                source_type="Assessment record",
                used_by_model=True,
                meaning=meaning,
                data_classification="raw_structured",
            )
        )
    return rows


