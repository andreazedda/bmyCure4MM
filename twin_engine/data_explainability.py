@dataclass(frozen=True)
class DataPointExplanation:
    label: str
    plain_name: str
    technical_field: str
    value_summary: str
    unit: str
    date_range: str
    n_records: int
    source_model: str
    source_table: str
    source_fields: list[str]
    data_classification: str
    used_by_model: bool
    used_in: list[str]
    why_it_matters: str
    what_missing_means: str
    next_action_if_missing: str
    source_rows_available: bool
    detail_anchor: str

    def as_dict(self) -> dict[str, Any]:
        payload = asdict(self)
        payload["data_classification_label"] = CLASSIFICATION_LABELS[self.data_classification]
        payload["used_in_display"] = [USED_IN_LABELS.get(value, value.replace("_", " ").title()) for value in self.used_in]
        payload["used_by_model_label"] = "Yes" if self.used_by_model else "No"
        return payload


