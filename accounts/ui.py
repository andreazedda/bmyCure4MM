def italian(value):
    text = str(value)
    if text in ITALIAN:
        return ITALIAN[text]
    length = re.fullmatch(r"Ensure this value has at (most|least) (\d+) characters \(it has (\d+)\)\.", text)
    if length:
        bound = "al massimo" if length[1] == "most" else "almeno"
        return f"Inserisci {bound} {length[2]} caratteri (ora sono {length[3]})."
    short = re.fullmatch(r"This password is too short. It must contain at least (\d+) characters\.", text)
    if short:
        return f"Password troppo corta: usa almeno {short[1]} caratteri."
    if text.startswith("The password is too similar to the "):
        return "La password è troppo simile alle informazioni dell’account."
    return text


def bilingual(value):
    text = str(value).replace("Scientific_Question", "Scientific question")
    translated = italian(text)
    if text == translated:
        return format_html("{}", text)
    return format_html('<span class="t-en">{}</span><span class="t-it">{}</span>', text, translated)
